import assert from 'node:assert/strict';
import { test } from 'node:test';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { commitWorkspace, distributionFixture } from './helpers/distribution-fixture.js';
import { ForkAPI } from './helpers/contribution-api.js';
import { systemCheck, systemUpdate, systemRollback, systemRead } from '../src/distribution/system.js';
import { prepareContribution, submitContribution } from '../src/distribution/contribute.js';
import { contextCapabilities } from '../src/services/context.js';
import { objectQuery, objectMutation } from '../src/services/objects.js';
import { writeAtomic } from '../src/distribution/common.js';

test('isolated lifecycle: older assistant entry -> runtime -> rollback -> upgrade -> reviewed contribution and retry', async t => {
  const f = await distributionFixture(t, { legacyEntry: true });
  assert.equal(existsSync(join(f.workspace, '.git')), false);
  assert.equal(objectQuery({ root: f.workspace, type: 'partner', operation: 'check', reference: 'partner.ksf.assistant' }).data.valid, true);
  assert.equal(objectQuery({ root: f.workspace, type: 'competency', operation: 'check', reference: 'competency.ksf.task-route' }).data.valid, true);
  writeAtomic(join(f.workspace, '知识/private.md'), 'FICTIONAL_PRIVATE_LIFECYCLE');
  const ignore = readFileSync(join(f.workspace, '.gitignore'));
  const next = await f.next();
  assert.equal((await systemCheck({ root: f.workspace, source: next.source })).available, true);
  assert.equal((await systemRead({ root: f.workspace })).version, '0.1.0');
  await systemUpdate({ root: f.workspace, from: next.coreArchive });
  assert.equal(existsSync(join(f.workspace, '.agents/core/abilities/partners/ksf-assistant/partner.md')), false);
  assert.throws(() => objectQuery({ root: f.workspace, type: 'partner', operation: 'read', reference: 'partner.ksf.assistant' }), { code: 'OBJECT_NOT_FOUND' });
  assert.throws(() => objectQuery({ root: f.workspace, type: 'competency', operation: 'read', reference: 'competency.ksf.task-route' }), { code: 'OBJECT_NOT_FOUND' });
  assert.equal(objectQuery({ root: f.workspace, type: 'competency', operation: 'check', reference: 'competency.ksf.ability-route@0.1.0' }).data.valid, true);
  const capabilities = contextCapabilities(f.workspace);
  assert.equal(capabilities.data.complete, true, JSON.stringify(capabilities.errors));
  const partners = capabilities.data.partners.objects;
  assert.equal(partners.find(p => p.id === 'partner.ksf.runtime').protected, true);
  assert.equal(partners.find(p => p.id === 'partner.ksf.maintainer').protected, false);
  const entry = objectQuery({ root: f.workspace, type: 'partner', operation: 'check', reference: 'partner.ksf.runtime' });
  assert.equal(entry.data.valid, true, JSON.stringify(entry.errors));
  assert.equal(f.launch(['runtime', 'verify', '--json']).status, 0);
  assert.equal(f.launch(['context', 'capabilities', '--json']).status, 0);
  await systemRollback({ root: f.workspace });
  assert.equal(objectQuery({ root: f.workspace, type: 'partner', operation: 'check', reference: 'partner.ksf.assistant' }).data.valid, true);
  await systemUpdate({ root: f.workspace, from: next.coreArchive });
  writeAtomic(join(f.workspace, '.agents/core/example.txt'), 'fictional reviewed improvement\n');
  commitWorkspace(f);
  const api = new ForkAPI({ coreRoot: f.root });
  const plan = await prepareContribution({ root: f.workspace, paths: ['.agents/core/example.txt'], api });
  const submitted = await submitContribution({ root: f.workspace, id: plan.id, reviewed: plan.digest, api });
  const retried = await submitContribution({ root: f.workspace, id: plan.id, reviewed: plan.digest, api });
  assert.equal(submitted.draft, true); assert.equal(retried.reused, true); assert.equal(api.prCount, 1);
  assert.ok(!JSON.stringify(api.calls).includes('FICTIONAL_PRIVATE_LIFECYCLE'));
  assert.equal(readFileSync(join(f.workspace, '知识/private.md'), 'utf8'), 'FICTIONAL_PRIVATE_LIFECYCLE');
  assert.ok(readFileSync(join(f.workspace, '.gitignore')).equals(ignore));
});

test('maintenance remains discoverable and derivable; runtime resists user takeover', async t => {
  const f = await distributionFixture(t);
  objectMutation({ root: f.workspace, type: 'partner', operation: 'write', id: 'partner.ksf.maintainer', input: { body: 'Fictional custom maintenance method.' } });
  const selected = objectQuery({ root: f.workspace, type: 'partner', operation: 'read', reference: 'partner.ksf.maintainer@0.1.4' });
  assert.equal(selected.data.object.source, 'user');
  assert.equal(contextCapabilities(f.workspace).data.partners.objects.find(p => p.id === 'partner.ksf.maintainer').protected, false);
  assert.throws(() => objectMutation({ root: f.workspace, type: 'partner', operation: 'write', id: 'partner.ksf.runtime', input: { body: 'replace' } }), { code: 'OBJECT_PROTECTED' });
});
