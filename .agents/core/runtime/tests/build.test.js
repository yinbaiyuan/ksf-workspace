test('invalid configuration and escaping paths do not overwrite the manifest', async t => {
  const f = fixture(t);
  f.config.runtime.packages['darwin-arm64'].archive_path = '../outside.tar.gz'; f.save();
  await assert.rejects(buildManifest(f.root), { code: 'BUILD_CONFIG_INVALID' });
  writeFileSync(join(f.root, '.agents/core/build.json'), 'invalid JSON');
  await assert.rejects(buildManifest(f.root), { code: 'BUILD_CONFIG_INVALID' });
  assert.equal(readFileSync(f.outputPath, 'utf8'), 'previous manifest\n');
});

test('source digest is stable across rebuilds and changes when system source changes', async t => {
  const f = fixture(t);
  const first = (await buildManifest(f.root)).manifest.build.source_sha256;
  assert.equal((await buildManifest(f.root)).manifest.build.source_sha256, first);
  writeFileSync(join(f.root, '.agents/core/runtime/src/cli.js'), '// changed source\n');
  assert.notEqual((await buildManifest(f.root)).manifest.build.source_sha256, first);
});

test('source digest follows the current root AGENTS.md entry', async t => {
  const f = fixture(t);
  const first = (await buildManifest(f.root)).manifest.build.source_sha256;
  writeFileSync(join(f.root, 'AGENTS.md'), '# KSF entry\n');
  const withEntry = (await buildManifest(f.root)).manifest.build.source_sha256;
  assert.notEqual(withEntry, first);
  writeFileSync(join(f.root, 'AGENTS.md'), '# Updated KSF entry\n');
  assert.notEqual((await buildManifest(f.root)).manifest.build.source_sha256, withEntry);
});

test('a symlink output is refused and its target remains unchanged', async t => {
  const f = fixture(t);
  const target = join(f.root, 'other-document');
  writeFileSync(target, 'preserve this file');
  rmSync(f.outputPath); symlinkSync(target, f.outputPath);
  await assert.rejects(buildManifest(f.root), { code: 'BUILD_OUTPUT_INVALID' });
  assert.equal(readFileSync(target, 'utf8'), 'preserve this file');
});

test('real ksf build recreates a missing or malformed manifest without global Node', { timeout: 60_000 }, t => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'ksf clean build 测试 ')));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(join(root, '.agents/bin'), { recursive: true });
  cpSync(join(repo, '.agents/bin/ksf'), join(root, '.agents/bin/ksf'));
  cpSync(join(repo, '.agents/core/runtime'), join(root, '.agents/core/runtime'), {
    recursive: true, filter: path => !path.includes('/packages') && !path.includes('/tests'),
  });
  cpSync(join(repo, '.agents/core/build.json'), join(root, '.agents/core/build.json'));
  const config = JSON.parse(readFileSync(join(root, '.agents/core/build.json'), 'utf8'));
  for (const item of Object.values(config.runtime.packages)) {
    mkdirSync(join(root, '.agents/core/runtime/packages'), { recursive: true });
    linkSync(join(repo, item.archive_path), join(root, item.archive_path));
  }
  const run = args => spawnSync(join(root, '.agents/bin/ksf'), args, {
    encoding: 'utf8', cwd: '/tmp', env: { ...process.env, PATH: '' }, timeout: 30_000,
  });
  const output = join(root, '.agents/core/manifest.yaml');
  assert.equal(existsSync(output), false);
  const first = run(['build', '--json']);
  assert.equal(first.status, 0, first.stderr);
  assert.equal(JSON.parse(first.stdout).manifest.build.generator, 'ksf build');
  let hello = run(['hello', '--json']);
  assert.equal(hello.status, 0, hello.stderr);
  assert.equal(JSON.parse(hello.stdout).message, 'Hello, KSF!');
  const generated = readFileSync(output);
  writeFileSync(output, 'broken YAML');
  assert.notEqual(run(['hello']).status, 0);
  const repaired = run(['build', '--json']);
  assert.equal(repaired.status, 0, repaired.stderr);
  hello = run(['hello', '--json']);
  assert.equal(hello.status, 0, hello.stderr);
  assert.notEqual(readFileSync(output, 'utf8'), 'broken YAML');
  const before = readFileSync(output);
  config.runtime.packages['darwin-arm64'].archive_sha256 = '0'.repeat(64);
  writeFileSync(join(root, '.agents/core/build.json'), JSON.stringify(config));
  const failed = run(['build', '--json']);
  assert.notEqual(failed.status, 0);
  assert.equal(failed.stdout, '');
  assert.deepEqual(readFileSync(output), before);
  assert.ok(generated.length > 0);
});
